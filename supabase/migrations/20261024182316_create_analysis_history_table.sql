/*
# Create public.analysis_history table

## Purpose
Stores non-sensitive analysis metadata for the MedScan AI research prototype.
This table holds ONLY metadata about analysis attempts (modality, file name,
file type, file size, status, timestamp, note). It does NOT store uploaded
medical images, identifiable patient data, or clinical report contents.

## 1. New Table: public.analysis_history
- id (uuid, primary key) — unique row id, generated by the database.
- modality (text, not null) — one of 'mri', 'histopathology', 'report'.
- file_name (text, not null) — name of the uploaded file (metadata only).
- file_type (text, not null) — MIME type of the uploaded file (metadata only).
- file_size (bigint, not null) — size of the uploaded file in bytes.
- status (text, not null) — analysis status, e.g. 'no_model', 'pending', 'failed'.
- note (text, not null) — short human-readable status note (no file contents).
- user_id (uuid, not null, defaults to the authenticated user) — owner of the row.
- created_at (timestamptz, default now()) — when the record was created.

## 2. Security
- Row Level Security is ENABLED on analysis_history.
- GRANT CRUD to the authenticated role only (no anon grants): this is an
  owner-scoped table for signed-in users. The anon-key client cannot read or
  write any rows until a user is authenticated.
- Four owner-scoped policies (one per CRUD verb) allow each authenticated user
  to access only the rows they own, keyed by user_id = auth.uid().
- The user_id column defaults to auth.uid() so inserts that omit it still
  satisfy the INSERT policy's WITH CHECK.
- No service_role grant is added because no edge function uses this table.

## 3. Important Notes
- This migration ONLY creates the table and its RLS policies. It does NOT
  modify application code, does NOT insert seed data, and does NOT create fake
  patient records.
- The MedScan AI frontend currently has no sign-in screen, so all requests run
  as the anon role and will be correctly denied by these policies. No records
  will be inserted or fetched through the app until an authenticated-user
  session and the corresponding auth flow are configured in a future step.
- Uploaded medical images and clinical report contents are never stored in
  this table — only lightweight metadata.
- MRI and histopathology AI predictions remain disabled; the status column
  is intended to record honest states such as 'no_model'.
*/

CREATE TABLE IF NOT EXISTS public.analysis_history (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  modality text NOT NULL CHECK (modality IN ('mri', 'histopathology', 'report')),
  file_name text NOT NULL,
  file_type text NOT NULL,
  file_size bigint NOT NULL CHECK (file_size >= 0),
  status text NOT NULL,
  note text NOT NULL DEFAULT '',
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS analysis_history_created_at_idx
  ON public.analysis_history (created_at DESC);
CREATE INDEX IF NOT EXISTS analysis_history_user_id_idx
  ON public.analysis_history (user_id);

ALTER TABLE public.analysis_history ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.analysis_history TO authenticated;

DROP POLICY IF EXISTS "select_own_analysis_history" ON public.analysis_history;
CREATE POLICY "select_own_analysis_history"
  ON public.analysis_history FOR SELECT
  TO authenticated
  USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "insert_own_analysis_history" ON public.analysis_history;
CREATE POLICY "insert_own_analysis_history"
  ON public.analysis_history FOR INSERT
  TO authenticated
  WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "update_own_analysis_history" ON public.analysis_history;
CREATE POLICY "update_own_analysis_history"
  ON public.analysis_history FOR UPDATE
  TO authenticated
  USING (auth.uid() = user_id)
  WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "delete_own_analysis_history" ON public.analysis_history;
CREATE POLICY "delete_own_analysis_history"
  ON public.analysis_history FOR DELETE
  TO authenticated
  USING (auth.uid() = user_id);
